function escapeHtml(text) {
  return String(text)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function scoreRelease(item) {
  let score = 0;
  if (item.statusKind === 'freeleech') score += 4;
  if (item.preferred) score += 2;
  if (item.inClient) score += 1;
  return score;
}

function renderStatusCell(item) {
  const parts = [];
  if (item.inClient) {
    parts.push('<span class="status-cell status-client">In client</span>');
  }
  if (item.statusKind === 'freeleech') {
    parts.push(`<span class="status-cell status-freeleech">${escapeHtml(item.status)}</span>`);
  } else if (item.statusKind === 'warning') {
    parts.push(`<span class="status-cell status-warning">${escapeHtml(item.status)}</span>`);
  } else {
    parts.push(`<span class="status-cell status-neutral">${escapeHtml(item.status)}</span>`);
  }
  return parts.join(' ');
}

function renderRow(item) {
  return `
    <div class="tracker-row">
      <span class="tracker-name">
        ${item.preferred ? '<span class="star-mark" aria-label="Preferred tracker">★</span>' : ''}
        <span>${escapeHtml(item.tracker)}</span>
      </span>
      <span class="row-release" title="${escapeHtml(item.name)}">${escapeHtml(item.name)}</span>
      <span class="row-stat">${escapeHtml(item.size)}</span>
      <span class="row-stat">${item.seeds} seeds</span>
      <div class="row-status">${renderStatusCell(item)}</div>
    </div>
  `;
}

function renderWorkbench() {
  const dataset = SEARCH_DATA[state.query];
  summaryEl.innerHTML = `
    <span class="summary-strong">${escapeHtml(dataset.summary)}</span>
    <span>Click any release group to inspect per-tracker copies</span>
  `;

  if (state.view === 'all') {
    const flat = dataset.groups.flatMap((g) => g.releases);
    const ordered = state.prioritize
      ? [...flat].sort((a, b) => scoreRelease(b) - scoreRelease(a) || b.seeds - a.seeds)
      : flat;
    resultsEl.innerHTML = ordered.map(renderRow).join('');
    return;
  }

  const orderedGroups = state.prioritize
    ? [...dataset.groups].sort((a, b) => {
        const aBest = Math.max(...a.releases.map(scoreRelease));
        const bBest = Math.max(...b.releases.map(scoreRelease));
        return bBest - aBest;
      })
    : dataset.groups;

  resultsEl.innerHTML = orderedGroups
    .map((group) => {
      const isOpen = state.openGroups.has(group.id);
      const releases = state.prioritize
        ? [...group.releases].sort((a, b) => scoreRelease(b) - scoreRelease(a) || b.seeds - a.seeds)
        : group.releases;
      const trackerNames = releases.map((r) => r.tracker).join(' · ');

      return `
        <div class="release-group ${isOpen ? 'is-open' : ''}">
          <button type="button" class="group-toggle" aria-expanded="${isOpen ? 'true' : 'false'}" data-group-id="${escapeHtml(group.id)}">
            <span class="group-watermark" aria-hidden="true">${escapeHtml(group.watermark)}</span>
            <span class="group-main">
              <span class="group-title">${escapeHtml(group.title)}</span>
              <span class="group-meta">
                <span>${releases.length} ${releases.length === 1 ? 'copy' : 'copies'}</span>
                <span>${escapeHtml(group.size)}</span>
                <span>${escapeHtml(trackerNames)}</span>
              </span>
            </span>
            <svg class="group-chevron" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true">
              <path d="m6 9 6 6 6-6"/>
            </svg>
          </button>
          <div class="group-rows">
            ${releases.map(renderRow).join('')}
          </div>
        </div>
      `;
    })
    .join('');

  resultsEl.querySelectorAll('.group-toggle').forEach((btn) => {
    btn.addEventListener('click', () => {
      const id = btn.dataset.groupId;
      if (state.openGroups.has(id)) {
        state.openGroups.delete(id);
      } else {
        state.openGroups.add(id);
      }
      renderWorkbench();
    });
  });
}

function bindSegmentedGroup(selector, onSelect) {
  const buttons = document.querySelectorAll(selector);
  buttons.forEach((btn) => {
    btn.addEventListener('click', () => {
      buttons.forEach((other) => {
        other.classList.remove('is-active');
        other.setAttribute('aria-selected', 'false');
      });
      btn.classList.add('is-active');
      btn.setAttribute('aria-selected', 'true');
      onSelect(btn);
    });
  });
}

bindSegmentedGroup('[data-query]', (btn) => {
  state.query = btn.dataset.query;
  state.openGroups.add(SEARCH_DATA[state.query].groups[0].id);
  renderWorkbench();
});

bindSegmentedGroup('[data-view]', (btn) => {
  state.view = btn.dataset.view;
  renderWorkbench();
});

prioritizeToggle.addEventListener('change', () => {
  state.prioritize = prioritizeToggle.checked;
  renderWorkbench();
});

bindSegmentedGroup('[data-shot]', (btn) => {
  const shot = SHOT_DATA[btn.dataset.shot];
  stageImageEl.src = shot.src;
  stageImageEl.alt = shot.alt;
});

bindSegmentedGroup('[data-theme-id]', (btn) => {
  const themeId = btn.dataset.themeId;
  document.documentElement.dataset.theme = themeId;
  stageImageEl.src = THEME_SHOTS[themeId];
  stageImageEl.alt = `xseek-match rendered in the ${themeId} theme`;
});

copyBtnEl.addEventListener('click', async () => {
  try {
    await navigator.clipboard.writeText(deployCodeEl.textContent);
    copyBtnEl.textContent = 'Copied';
    setTimeout(() => {
      copyBtnEl.textContent = 'Copy';
    }, 1600);
  } catch {
    copyBtnEl.textContent = 'Select manually';
    setTimeout(() => {
      copyBtnEl.textContent = 'Copy';
    }, 1600);
  }
});

renderWorkbench();
